/**
 * Generate SubRip (.srt) subtitle content with word or phrase timestamps
 */
export function generateSRT(words: TimedWord[]): string {
  const formatSrtTime = (ms: number) => {
    const totalSec = Math.floor(ms / 1000);
    const m = Math.floor(totalSec / 60);
    const s = totalSec % 60;
    const mill = ms % 1000;
    return `00:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')},${mill.toString().padStart(3, '0')}`;
  };

  return words
    .map((w, index) => {
      return `${index + 1}\n${formatSrtTime(w.startMs)} --> ${formatSrtTime(w.endMs)}\n${w.word}\n`;
    })
    .join('\n');
}

/**
 * Generate Advanced SubStation Alpha (.ass) subtitle file with Ruq'ah / Diwani calligraphy styling & karaoke tags
 */
export function generateASS(words: TimedWord[], fontName: string = 'Aref Ruqaa'): string {
  const formatAssTime = (ms: number) => {
    const totalSec = Math.floor(ms / 1000);
    const h = Math.floor(totalSec / 3600);
    const m = Math.floor((totalSec % 3600) / 60);
    const s = totalSec % 60;
    const cs = Math.floor((ms % 1000) / 10);
    return `${h}:${m.toString().padStart(2, '0')}:${s.toString().padStart(2, '0')}.${cs.toString().padStart(2, '0')}`;
  };

  const header = `[Script Info]
; Script generated by Sheikh Al-Eid Studio - Handwriting Calligraphy
Title: Sheikh Eid Animated Calligraphy
ScriptType: v4.00+
PlayResX: 1080
PlayResY: 1920
ScaledBorderAndShadow: yes

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: DiwaniCalligraphy,${fontName},68,&H009EDFFF,&H00FFFFFF,&H00000000,&H80000000,-1,0,0,0,100,100,2,0,1,3,4,5,40,40,380,1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  // Generate karaoke line where each word highlights with {\k<centiseconds>}
  const startTime = words.length > 0 ? formatAssTime(words[0].startMs) : '0:00:00.00';
  const endTime = words.length > 0 ? formatAssTime(words[words.length - 1].endMs + 1000) : '0:00:10.00';

  let karaokeText = '';
  words.forEach((w) => {
    const durCs = Math.round((w.endMs - w.startMs) / 10);
    karaokeText += `{\\k${durCs}}${w.word} `;
  });

  const dialogue = `Dialogue: 0,${startTime},${endTime},DiwaniCalligraphy,,0,0,0,,${karaokeText.trim()}`;

  return header + dialogue;
}
